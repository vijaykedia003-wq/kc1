# Standardize the primary 'Back Office Code' column and the 'Holding Value'
clean_holding_temp['Back Office Code'] = clean_holding_temp['Back Office Code'].astype(str).str.strip()
clean_holding_temp['Holding Value'] = pd.to_numeric(clean_holding_temp['Holding Value'], errors='coerce').fillna(0)

# Aggregate holdings per client
holding_sum = clean_holding_temp.groupby('Back Office Code')['Holding Value'].sum().reset_index()

# Merge UCC with holdings
merged_df = pd.merge(ucc_combine_df, holding_sum, left_on='Client Code', right_on='Back Office Code', how='left')
merged_df['Holding Value'] = merged_df['Holding Value'].fillna(0)

