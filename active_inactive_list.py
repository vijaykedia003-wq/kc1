active_clients = set(segment_activation_df['Client Code'].unique())

def classify_status(row):
    if str(row['Status']).strip().lower() == 'disabled':
        return 'Disabled'
    elif row['Client Code'] in active_clients:
        return 'Active'
    else:
        return 'Inactive'

merged_df['Activity Status'] = merged_df.apply(classify_status, axis=1)

